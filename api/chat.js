function getClientIP(request) {

    const forwarded =
        request.headers.get("x-forwarded-for");

    if (forwarded) {

        return forwarded
            .split(",")[0]
            .trim();

    }

    return "unknown";
}


export default async function handler(request, response) {

    if (request.method !== "POST") {

        return response
            .status(405)
            .json({
                error:"Method Not Allowed"
            });

    }


    try {

        const body =
            request.body || {};

        const message =
            typeof body.message === "string"
                ? body.message.trim()
                : "";


        if (!message) {

            return response
                .status(400)
                .json({
                    error:"الرسالة فارغة"
                });

        }


        if (message.length > 1500) {

            return response
                .status(413)
                .json({
                    error:"الرسالة طويلة جداً"
                });

        }


        /*
         * منع الطلبات المتكررة جداً من نفس المصدر
         * حماية بسيطة على مستوى الوظيفة.
         */

        const ip =
            getClientIP(request);

        /*
         * يمكن لاحقاً ربط هذا المكان
         * بـ Redis / KV لتطبيق Rate Limit
         * حقيقي لكل IP.
         */


        const result =
            await client.responses.create({

                model:"gpt-5.6-luna",

                instructions:
                    SYSTEM_INSTRUCTIONS,

                input:[
                    {
                        role:"user",
                        content:message
                    }
                ],

                max_output_tokens:700

            });


        const reply =
            typeof result.output_text === "string"
                ? result.output_text.trim()
                : "";


        if (!reply) {

            throw new Error(
                "Empty AI response"
            );

        }


        return response
            .status(200)
            .json({
                reply:reply
            });


    } catch(error) {

        console.error(
            "AI error:",
            error?.message || error
        );


        return response
            .status(500)
            .json({
                error:
                    "حدث خطأ مؤقت في المستشار."
            });

    }

}
